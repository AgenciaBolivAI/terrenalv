-- EL PLAN DE CUENTAS QUE MANDARON.
--
-- La estructura para un plan jerárquico ya estaba (parent_code, moneda,
-- centro de costos, la regla de que solo se asienta en cuentas hoja). Lo que
-- faltaba era el CONTENIDO: las cuentas del plan de Las Lomas, que es el plan
-- que la contadora conoce y contra el que revisa. Teníamos 31; el plan trae
-- 388.
--
-- Cómo conviven con las nuestras:
--
--   · El árbol y los códigos son los del plan (1.02.01.010). Eso es lo que se
--     ve en pantalla y en los reportes: `codigo_plan`.
--   · Nuestras 31 cuentas operativas NO cambian de código interno. El diario
--     automático, `verificar_integridad` y los guardianes nombran a la 1131
--     por su código; renombrarla sería mover el piso de toda la contabilidad
--     por una cuestión de presentación. Cada una se cuelga del grupo que le
--     corresponde y lleva su `codigo_plan` al lado (ver la migración
--     siguiente, que las acomoda).
--   · Donde el plan ya trae la cuenta que usamos, NO se duplica: la nuestra
--     toma ese código de plan (1131 → 1.02.01.010). Donde tenemos un concepto
--     que el plan no contempla —interés de financiamiento, comisión del
--     mercado de traspasos, penalidades por anulación— se le da un código
--     libre dentro del grupo correcto.
--   · Las urbanizaciones del 1.05.02 son las de Las Lomas. Van las nuestras.
--
-- Los nombres van tal cual el PDF, con sus mayúsculas y sus erratas
-- («CLENTES», «ALQUUILERES», «DESHAUCIO»): la contadora coteja las dos listas
-- línea por línea y tienen que coincidir.

alter table public.chart_of_accounts
  add column if not exists codigo_plan text;

comment on column public.chart_of_accounts.codigo_plan is
  'El código en el plan de cuentas (1.02.01.010) — es el que se muestra. '
  '`code` es la llave interna, que para las cuentas del sistema sigue siendo '
  'el código corto que nombra el diario automático.';

create unique index if not exists chart_codigo_plan_uidx
  on public.chart_of_accounts (codigo_plan) where codigo_plan is not null;

-- Las cuentas de orden (6 y 7) no son activo/pasivo/patrimonio/ingreso/gasto:
-- son memorándum fuera de balance. El plan las trae, así que la naturaleza
-- tiene que admitirlas.
alter table public.chart_of_accounts drop constraint if exists chart_of_accounts_kind_check;
alter table public.chart_of_accounts add constraint chart_of_accounts_kind_check
  check (kind in ('activo','pasivo','patrimonio','ingreso','gasto',
                  'orden_deudora','orden_acreedora'));

